# dataviz/smart/ - "עורך הגרפים החכם" (סבב 20.10.2026): מתיקיית נתונים לטיוטת פרק מוכנה, כשכל בחירה אוטומטית מוסברת
# (סיבה + ביטחון) כדי שהמשתמש רק יאשר או יתקן. הכל קריאה בלבד מתיקיית המקור; הטיוטה נשמרת כקובץ שינויים (overrides).
#   scan     - סיווג הקבצים בתיקייה (סדרה / אירועים / משקלות / גולמי שלא בשימוש / בדיקה / מסמכים)
#   columns  - תפקיד כל עמודה (זמן / ישות / ערך), יחידות, ועוד - כל אחד עם ביטחון וסיבה
